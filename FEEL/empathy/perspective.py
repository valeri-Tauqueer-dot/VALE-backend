"""
VALE FEELINGS Brain
Empathy Perspective Model

File:
    FEEL/empathy/perspective.py

Purpose:
    Model another person's possible perspective of a situation.

Core principle:

    OBSERVED INFORMATION
            ↓
    CONTEXT
            ↓
    POSSIBLE PERSPECTIVES
            ↓
    POSSIBLE INTERPRETATIONS
            ↓
    UNCERTAINTY
            ↓
    COMMUNICATION IMPLICATIONS

This subsystem does not claim to know what another person actually thinks
or feels. It generates bounded perspective hypotheses from available
evidence and context.

Important epistemic boundary:

    FACT != INFERENCE != HYPOTHESIS

A perspective generated by this module is an inference/hypothesis unless
the person explicitly stated it.
"""

