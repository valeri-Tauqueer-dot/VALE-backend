    def _generate_inferred_perspectives(
        self,
        text: str,
    ) -> List[PerspectiveSignal]:
        """
        Generate possible interpretations from observable language.

        These are deliberately hypotheses rather than conclusions.
        """

        perspectives: List[PerspectiveSignal] = []

        concern_categories = self._detect_categories(
            text,
            self.CONCERN_PATTERNS,
        )

        priority_categories = self._detect_categories(
            text,
            self.PRIORITY_PATTERNS,
        )

        # --------------------------------------------------------------
        # Risk
        # --------------------------------------------------------------

        if "risk" in concern_categories:
            perspectives.append(
                PerspectiveSignal(
                    perspective="risk-sensitive perspective",
                    interpretation=(
                        "The person may be evaluating the situation "
                        "primarily through possible negative consequences."
                    ),
                    confidence=0.55,
                    relevance=0.75,
                    alternative_explanations=[
                        "Risk-related wording may simply describe "
                        "the task rather than the person's perspective."
                    ],
                    uncertainties=[
                        "No direct statement confirms that risk is "
                        "the person's dominant concern."
                    ],
                )
            )

        # --------------------------------------------------------------
        # Uncertainty
        # --------------------------------------------------------------

        if "uncertainty" in concern_categories:
            perspectives.append(
                PerspectiveSignal(
                    perspective="uncertainty-sensitive perspective",
                    interpretation=(
                        "The person may primarily need clearer "
                        "information or reduced ambiguity."
                    ),
                    confidence=0.62,
                    relevance=0.78,
                    alternative_explanations=[
                        "The wording may reflect ordinary information "
                        "seeking rather than significant uncertainty."
                    ],
                    uncertainties=[
                        "The available text does not establish the "
                        "degree of uncertainty."
                    ],
                )
            )

        # --------------------------------------------------------------
        # Time pressure
        # --------------------------------------------------------------

        if "time" in concern_categories:
            perspectives.append(
                PerspectiveSignal(
                    perspective="time-sensitive perspective",
                    interpretation=(
                        "The person may place significant value on "
                        "speed or immediate progress."
                    ),
                    confidence=0.64,
                    relevance=0.8,
                    alternative_explanations=[
                        "Urgency language may describe task constraints "
                        "rather than emotional pressure."
                    ],
                )
            )

        # --------------------------------------------------------------
        # Accuracy
        # --------------------------------------------------------------

        if "accuracy" in concern_categories:
            perspectives.append(
                PerspectiveSignal(
                    perspective="accuracy-sensitive perspective",
                    interpretation=(
                        "The person may prioritize correctness, "
                        "verification, or avoiding mistakes."
                    ),
                    confidence=0.66,
                    relevance=0.82,
                    alternative_explanations=[
                        "Accuracy language may be a normal requirement "
                        "of the task rather than a personal concern."
                    ],
                )
            )

        # --------------------------------------------------------------
        # Control
        # --------------------------------------------------------------

        if "control" in concern_categories:
            perspectives.append(
                PerspectiveSignal(
                    perspective="autonomy/control perspective",
                    interpretation=(
                        "The person may place importance on retaining "
                        "choice or understanding available options."
                    ),
                    confidence=0.53,
                    relevance=0.68,
                    alternative_explanations=[
                        "Decision language may be purely task-oriented."
                    ],
                )
            )

        # --------------------------------------------------------------
        # Understanding
        # --------------------------------------------------------------

        if "understanding" in concern_categories:
            perspectives.append(
                PerspectiveSignal(
                    perspective="understanding-oriented perspective",
                    interpretation=(
                        "The person may primarily need a clear "
                        "explanation rather than only an answer."
                    ),
                    confidence=0.69,
                    relevance=0.84,
                    alternative_explanations=[
                        "A question may simply request a concise fact."
                    ],
                )
            )

        # --------------------------------------------------------------
        # Outcome
        # --------------------------------------------------------------

        if "outcome" in concern_categories:
            perspectives.append(
                PerspectiveSignal(
                    perspective="outcome-oriented perspective",
                    interpretation=(
                        "The person may be focused on the practical "
                        "result or consequence of the situation."
                    ),
                    confidence=0.56,
                    relevance=0.72,
                    alternative_explanations=[
                        "Outcome-related language may simply reflect "
                        "the structure of the task."
                    ],
                )
            )

        return perspectives

