@dataclass
class PerspectiveSignal:
    """
    A single possible perspective or interpretation.

    `is_explicit` means the perspective is directly supported by an
    explicit statement from the person.

    Otherwise it should be treated as an inference/hypothesis.
    """

    perspective: str

    interpretation: str

    confidence: float = 0.0

    relevance: float = 0.0

    is_explicit: bool = False

    evidence: List[EvidenceReference] = field(default_factory=list)

    alternative_explanations: List[str] = field(
        default_factory=list
    )

    uncertainties: List[str] = field(
        default_factory=list
    )

    metadata: Dict[str, Any] = field(
        default_factory=dict
    )

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


