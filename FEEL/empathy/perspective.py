    # ------------------------------------------------------------------
    # Input handling
    # ------------------------------------------------------------------

    def _extract_text(self, context: Any) -> str:
        """
        Extract conversational text from common VALE context structures.
        """

        if context is None:
            return ""

        if isinstance(context, str):
            return context.strip()

        if isinstance(context, Mapping):
            for key in (
                "text",
                "message",
                "user_message",
                "content",
                "query",
                "situation",
            ):
                value = _safe_text(context.get(key))

                if value:
                    return value

            return ""

        for attribute in (
            "text",
            "message",
            "user_message",
            "content",
            "query",
            "situation",
        ):
            if hasattr(context, attribute):
                value = _safe_text(
                    getattr(context, attribute)
                )

                if value:
                    return value

        return ""

    def _extract_observations(
        self,
        context: Any,
        text: str,
    ) -> List[str]:
        """
        Extract only observable/explicit information.

        This method intentionally does not convert assumptions into facts.
        """

        observations: List[str] = []

        if text:
            observations.append(
                f"User provided: {text}"
            )

        if isinstance(context, Mapping):
            explicit_keys = (
                "observed_events",
                "known_context",
                "facts",
                "explicit_information",
                "constraints",
            )

            for key in explicit_keys:
                value = context.get(key)

                if isinstance(value, Sequence) and not isinstance(
                    value,
                    (str, bytes),
                ):
                    observations.extend(
                        _safe_text(item)
                        for item in value
                        if _safe_text(item)
                    )

                elif value:
                    observations.append(
                        _safe_text(value)
                    )

        return _unique(observations)

    # ------------------------------------------------------------------
    # Pattern detection
    # ------------------------------------------------------------------

    def _contains_pattern(
        self,
        text: str,
        pattern: str,
    ) -> bool:
        return pattern.casefold() in text.casefold()

    def _detect_categories(
        self,
        text: str,
        patterns: Mapping[str, Sequence[str]],
    ) -> List[str]:
        categories: List[str] = []

        for category, category_patterns in patterns.items():
            if any(
                self._contains_pattern(text, pattern)
                for pattern in category_patterns
            ):
                categories.append(category)

        return categories

    # ------------------------------------------------------------------
    # Explicit perspective extraction
    # ------------------------------------------------------------------

    def _extract_explicit_perspective(
        self,
        context: Any,
    ) -> List[PerspectiveSignal]:
        """
        Extract perspective statements that were explicitly supplied.

        Supported fields:

            explicit_perspective
            explicit_perspectives
            stated_feelings
            stated_concerns
            stated_priorities
            user's_perspective
        """

        perspectives: List[PerspectiveSignal] = []

        if not isinstance(context, Mapping):
            return perspectives

        explicit_keys = (
            "explicit_perspective",
            "explicit_perspectives",
            "stated_feelings",
            "stated_concerns",
            "stated_priorities",
            "user_perspective",
            "users_perspective",
        )

        for key in explicit_keys:
            value = context.get(key)

            if value is None:
                continue

            values: List[Any]

            if isinstance(value, Sequence) and not isinstance(
                value,
                (str, bytes),
            ):
                values = list(value)
            else:
                values = [value]

            for item in values:
                text = _safe_text(item)

                if not text:
                    continue

                perspectives.append(
                    PerspectiveSignal(
                        perspective="explicit user perspective",
                        interpretation=text,
                        confidence=1.0,
                        relevance=1.0,
                        is_explicit=True,
                        uncertainties=[],
                        alternative_explanations=[],
                        metadata={
                            "source": key,
                            "epistemic_type": (
                                EpistemicType.FACT.value
                                if hasattr(
                                    EpistemicType,
                                    "value",
                                )
                                else "fact"
                            ),
                        },
                    )
                )

        return perspectives

