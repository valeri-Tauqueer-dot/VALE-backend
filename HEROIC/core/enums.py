LEVELS = ("CRITICAL", "HIGH", "NORMAL", "LOW", "BACKGROUND")


def lower_level(level: str, steps: int = 1) -> str:
    try:
        return LEVELS[min(LEVELS.index(level) + steps, len(LEVELS) - 1)]
    except ValueError:
        return "NORMAL"
